using UnityEngine;

namespace Rihla
{
    /// <summary>
    /// Where a game that uses the shared core keeps its own files, and the few names that differ between games.
    /// Rihla has no config asset, so every value below is Rihla's own and Rihla works exactly as before. Another game
    /// (Road to AlQuds) puts a RihlaCoreConfig asset in a Resources folder (for example
    /// Assets/AlQuds/Resources/RihlaCoreConfig.asset) with its own values.
    /// </summary>
    [CreateAssetMenu(fileName = "RihlaCoreConfig", menuName = "Rihla Core/Core config")]
    public class CoreConfig : ScriptableObject
    {
        /// <summary>The name of the asset in a Resources folder that the core looks for.</summary>
        public const string ResourceName = "RihlaCoreConfig";

        [Tooltip("The game's name, for logs and messages.")]
        public string gameName = "Rihla";
        [Tooltip("The game's own folder under Assets; the folders below default to sub-folders of it.")]
        public string gameRoot = "Assets/Rihla/";
        [Tooltip("The content copied from content/ by the export tool. Empty: <gameRoot>Content/")]
        public string contentFolder = "";
        [Tooltip("Panel settings and theme for the bilingual interface. Empty: <gameRoot>UI/")]
        public string uiFolder = "";
        [Tooltip("The Amiri typefaces. Empty: <gameRoot>Fonts/")]
        public string fontsFolder = "";
        [Tooltip("Data generated by the export tool (terrain, roads). Empty: <gameRoot>Generated/")]
        public string generatedFolder = "";
        [Tooltip("Meshes and materials made by the scene builders (not in git). Empty: <gameRoot>Built/")]
        public string builtFolder = "";
        [Tooltip("Textures. Empty: <gameRoot>Textures/")]
        public string texturesFolder = "";
        [Tooltip("Where the scene builders save scenes.")]
        public string scenesFolder = "Assets/Scenes/";
        [Tooltip("The URP renderer that the render setup menus change.")]
        public string rendererPath = "Assets/Settings/PC_Renderer.asset";
        [Tooltip("Git-ignored files in StreamingAssets holding the map keys.")]
        public string cesiumIonTokenFile = "cesium_ion_token.txt", googleMapsKeyFile = "google_maps_key.txt";
        [Tooltip("The PlayerPrefs key of the save.")]
        public string saveKey = "rihla.save.v1";
        [Tooltip("Show Rihla's chapter list (the journey) in the menu.")]
        public bool showJourneyInMenu = true;
        [Tooltip("Enable Rihla's own scene-builder menus (Rihla > Build ...). Off in other games.")]
        public bool rihlaBuilderMenus = true;

        static CoreConfig current;

        /// <summary>The game's config: the RihlaCoreConfig asset in a Resources folder, or Rihla's defaults.</summary>
        public static CoreConfig Current
        {
            get
            {
                if (current) return current;
                current = Resources.Load<CoreConfig>(ResourceName);
                if (!current) { current = CreateInstance<CoreConfig>(); current.hideFlags = HideFlags.DontSave; }
                return current;
            }
        }

        static string Or(string value, string sub) => string.IsNullOrEmpty(value) ? Slash(Current.gameRoot) + sub : Slash(value);
        static string Slash(string p) => string.IsNullOrEmpty(p) || p.EndsWith("/") ? p : p + "/";

        public static string Content => Or(Current.contentFolder, "Content/");
        public static string UI => Or(Current.uiFolder, "UI/");
        public static string Fonts => Or(Current.fontsFolder, "Fonts/");
        public static string Generated => Or(Current.generatedFolder, "Generated/");
        public static string Built => Or(Current.builtFolder, "Built/");
        public static string Textures => Or(Current.texturesFolder, "Textures/");
        public static string Scenes => Slash(Current.scenesFolder);
    }
}
